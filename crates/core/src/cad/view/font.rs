/// The rows of `ch`, or none for a space.
fn glyph(ch: char) -> Option<[u8; 7]> {
    if ch == ' ' {
        return None;
    }
    let upper = ch.to_ascii_uppercase();
    GLYPHS
        .iter()
        .find(|(known, _)| *known == upper)
        .or_else(|| GLYPHS.iter().find(|(known, _)| *known == '?'))
        .map(|(_, rows)| *rows)
}

/// Does the font have a glyph of its own for `ch`?
#[cfg(test)]
pub(super) fn covers(ch: char) -> bool {
    ch == ' '
        || GLYPHS
            .iter()
            .any(|(known, _)| *known == ch.to_ascii_uppercase())
}

/// Width in pixels of `text` at scale `k`.
pub(super) fn width(text: &str, k: usize) -> usize {
    text.chars().count() * ADVANCE * k
}

/// The longest start of `text` that fits `pixels` at scale `k`.
pub(super) fn clip(text: &str, pixels: usize, k: usize) -> &str {
    let fits = pixels / (ADVANCE * k);
    match text.char_indices().nth(fits) {
        Some((at, _)) => text[..at].trim_end(),
        None => text,
    }
}

/// Draw `text` with its top left corner at (x, y). `plot` sets one pixel.
pub(super) fn draw(text: &str, x: i64, y: i64, k: usize, plot: &mut impl FnMut(i64, i64)) {
    let k = k as i64;
    for (index, ch) in text.chars().enumerate() {
        let Some(rows) = glyph(ch) else {
            continue;
        };
        let left = x + index as i64 * ADVANCE as i64 * k;
        for (row, bits) in rows.iter().enumerate() {
            for column in 0..5 {
                if bits & (0x10 >> column) == 0 {
                    continue;
                }
                for dy in 0..k {
                    for dx in 0..k {
                        plot(left + column * k + dx, y + row as i64 * k + dy);
                    }
                }
            }
        }
    }
}
