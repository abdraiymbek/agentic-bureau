//! A 5×7 bitmap font for the text drawn into pictures: capitals, digits and
//! the few signs a drawing label needs. Lowercase is drawn as uppercase and
//! any other character as `?`. Glyphs are scaled by an integer factor.

/// Pixels from one glyph to the next and from one line to the next, at scale 1.
pub(super) const ADVANCE: usize = 6;
pub(super) const LINE: usize = 9;
/// Height of a glyph at scale 1.
pub(super) const HEIGHT: usize = 7;

